#include "crypto_manager.h"
#include "aes.h"
#include "hmac_sha256.h"

const uint8_t OTA_AES_Key[32] =
{
    0x01, 0x02, 0x03, 0x04,
    0x05, 0x06, 0x07, 0x08,
    0x09, 0x0A, 0x0B, 0x0C,
    0x0D, 0x0E, 0x0F, 0x10,
    0x11, 0x12, 0x13, 0x14,
    0x15, 0x16, 0x17, 0x18,
    0x19, 0x1A, 0x1B, 0x1C,
    0x1D, 0x1E, 0x1F, 0x20
};

const uint8_t OTA_Default_IV[16] =
{
    0x00, 0x01, 0x02, 0x03,
    0x04, 0x05, 0x06, 0x07,
    0x08, 0x09, 0x0A, 0x0B,
    0x0C, 0x0D, 0x0E, 0x0F
};

const uint8_t OTA_HMAC_Key[32] =
{
    0xA1, 0xA2, 0xA3, 0xA4,
    0xA5, 0xA6, 0xA7, 0xA8,
    0xA9, 0xAA, 0xAB, 0xAC,
    0xAD, 0xAE, 0xAF, 0xB0,
    0xB1, 0xB2, 0xB3, 0xB4,
    0xB5, 0xB6, 0xB7, 0xB8,
    0xB9, 0xBA, 0xBB, 0xBC,
    0xBD, 0xBE, 0xBF, 0xC0
};

uint8_t Crypto_VerifyHMAC(
        const uint8_t *data,
        uint32_t length,
        const uint8_t *expectedHMAC)
{
    return HMAC_SHA256_Verify(
            OTA_HMAC_Key,
            sizeof(OTA_HMAC_Key),
            data,
            length,
            expectedHMAC);
}

uint8_t Crypto_DecryptFirmware(
        uint8_t *buffer,
        uint32_t length,
        const uint8_t *iv)
{
    struct AES_ctx ctx;

    AES_init_ctx_iv(
            &ctx,
            OTA_AES_Key,
            iv);

    AES_CBC_decrypt_buffer(
            &ctx,
            buffer,
            length);

    return 1;
}
